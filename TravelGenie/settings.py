# Database
# https://docs.djangoproject.com/en/4.2/ref/settings/#databases

if os.environ.get('DATABASE_URL'):
    from urllib.parse import urlparse, parse_qs
    url = os.environ.get('DATABASE_URL')
    parsed = urlparse(url)
    qs = parse_qs(parsed.query)
    options = {}
    if 'sslmode' in qs:
        options['sslmode'] = qs['sslmode'][0]
    
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': parsed.path.lstrip('/'),
            'USER': parsed.username,
            'PASSWORD': parsed.password,
            'HOST': parsed.hostname,
            'PORT': parsed.port or 5432,
            'OPTIONS': options,
            'CONN_MAX_AGE': 600,
        }
    }

else:
    # On Vercel / AWS Lambda, the root filesystem (/var/task) is strictly read-only.
    # We copy the pre-seeded SQLite database to the writable /tmp directory.
    is_serverless = (
        os.environ.get('VERCEL')
        or os.environ.get('AWS_LAMBDA_FUNCTION_NAME')
        or os.environ.get('LAMBDA_TASK_ROOT')
        or str(BASE_DIR).startswith('/var/task')
        or not os.access(str(BASE_DIR), os.W_OK)
    )
    if is_serverless:
        tmp_db = '/tmp/db.sqlite3'
        orig_db = os.path.join(BASE_DIR, 'db.sqlite3')
        if not os.path.exists(tmp_db) or os.path.getsize(tmp_db) == 0:
            if os.path.exists(orig_db):
                shutil.copyfile(orig_db, tmp_db)
                try:
                    os.chmod(tmp_db, 0o666)
                except Exception:
                    pass
        db_path = tmp_db
    else:
        db_path = BASE_DIR / 'db.sqlite3'

    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': db_path,
        }
    }

